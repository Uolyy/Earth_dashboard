"""
Конфигурация проекта «Орбитальный пост наблюдения».

Модуль собирает все настройки в одном месте, чтобы остальной код
не содержал «магических» чисел и строковых литералов.

Настройки читаются из двух источников, по убыванию приоритета:

1. Переменные окружения (в том числе из файла `.env` в корне проекта).
2. Значения по умолчанию, заданные ниже.

Проект сознательно работает без единого обязательного ключа:
каждый внешний источник данных используется в своём бесплатном
общедоступном режиме, не требующем регистрации.
"""

from __future__ import annotations

import os
from pathlib import Path

from dotenv import load_dotenv

# Корневая директория проекта (на уровень выше директории backend).
PROJECT_ROOT: Path = Path(__file__).resolve().parent.parent

# Загружаем значения из файла `.env`, если он существует.
# Параметр `override=False` означает, что реальные переменные окружения
# имеют приоритет над значениями из файла.
load_dotenv(PROJECT_ROOT / '.env', override=False)


def _read_int(name: str, default: int) -> int:
    """
    Читает целочисленную настройку из переменной окружения.

    Parameters
    ----------
    name : str
        Имя переменной окружения.
    default : int
        Значение, используемое, если переменная отсутствует либо
        не может быть преобразована в целое число.

    Returns
    -------
    int
        Значение настройки.
    """
    raw_value = os.getenv(name)
    if raw_value is None:
        return default
    try:
        return int(raw_value)
    except ValueError:
        return default


# ---------------------------------------------------------------------------
# Сетевые настройки
# ---------------------------------------------------------------------------

#: Адрес, на котором сервер принимает соединения по умолчанию.
HOST: str = os.getenv('DASHBOARD_HOST', '127.0.0.1')

#: Порт, на котором запускается веб-сервер.
PORT: int = _read_int('DASHBOARD_PORT', 8000)

#: Таймаут одного HTTP-запроса к внешнему источнику, в секундах.
#: Относительно небольшое значение нужно для того, чтобы медленно
#: отвечающий внешний сервис не подвешивал отрисовку интерфейса.
HTTP_TIMEOUT_SECONDS: float = float(os.getenv('HTTP_TIMEOUT_SECONDS', '15'))

#: Сколько раз клиент повторяет запрос при сетевой ошибке или таймауте.
HTTP_RETRIES: int = _read_int('HTTP_RETRIES', 2)

#: Пауза между повторными попытками, в секундах.
HTTP_RETRY_DELAY_SECONDS: float = float(os.getenv('HTTP_RETRY_DELAY_SECONDS', '1.0'))


# ---------------------------------------------------------------------------
# Настройки кэширования
# ---------------------------------------------------------------------------

#: Директория, в которой сохраняются ответы внешних источников.
#: Кэш на диске нужен по двум причинам: он снижает нагрузку на
#: внешние сервисы и позволяет приложению пережить перезапуск
#: без повторного обращения ко всем источникам.
CACHE_DIRECTORY: Path = PROJECT_ROOT / '.cache'

#: Срок жизни записи кэша в секундах, если он не задан явно.
CACHE_TTL_SECONDS: int = _read_int('CACHE_TTL_SECONDS', 900)


# ---------------------------------------------------------------------------
# Внешние источники данных
# ---------------------------------------------------------------------------

#: Идентификатор МКС в каталоге NORAD.
#: По этому номеру большинство сервисов определяет нужный аппарат.
ISS_NORAD_ID: int = _read_int('ISS_NORAD_ID', 25544)

#: Источник телеметрии МКС: координаты, высота, скорость, освещённость.
ISS_TELEMETRY_URL: str = 'https://api.wheretheiss.at/v1/satellites/{norad_id}'

#: Источник списка людей на борту станции.
#: Обращается по протоколу HTTP и не отдаёт заголовков CORS,
#: поэтому используется исключительно через собственный API.
OPEN_NOTIFY_CREW_URL: str = 'http://api.open-notify.org/astros.json'

#: Базовый адрес службы прогнозов космической погоды.
#: Сервис публикует индекс геомагнитной активности, прогноз магнитных
#: бурь и данные солнечного цикла.
SPACE_WEATHER_BASE_URL: str = 'https://services.swpc.noaa.gov'

#: Адрес расписания предстоящих запусков ракет.
#: Параметр `mode=list` намеренно не используется: он сокращает объём
#: ответа, но заменяет вложенные объекты (площадку, ракету-носитель)
#: обычными строками, из-за чего часть сведений оказывается
#: недоступна. Полный ответ окупается за счёт кэширования.
LAUNCHES_URL: str = (
    'https://ll.thespacedevs.com/2.2.0/launch/upcoming/'
    '?limit={limit}'
)

#: Адрес источника сведений об околоземных астероидах.
#: Обращается без ключа доступа и без ограничения частоты запросов.
ASTEROIDS_URL: str = (
    'https://ssd-api.jpl.nasa.gov/sbdb_query.api'
    '?fields=full_name,pdes,name,neo,pha,H,diameter,class'
    '&sb-group={group}&limit={limit}'
)

#: Адрес источника подробных сведений об одном астероиде.
#: В отличие от обзорной выборки, этот адрес возвращает физические
#: параметры тела и полную историю сближений с Землёй.
#: Обращается без ключа доступа и без ограничения частоты запросов.
ASTEROID_DETAILS_URL: str = (
    'https://ssd-api.jpl.nasa.gov/sbdb.api'
    '?sstr={designation}&phys-par=1&ca-data=1'
)

#: Адрес источника двухстрочных элементов орбиты (TLE) МКС.
#: Формат TLE — компактное описание орбиты аппарата, позволяющее
#: вычислить его положение в любой момент времени.
ISS_TLE_URL: str = (
    'https://celestrak.org/NORAD/elements/gp.php?CATNR={norad_id}&FORMAT=TLE'
)

#: Адрес каталога группировок спутников на околоземных орбитах.
SATELLITE_GROUPS_URL: str = (
    'https://celestrak.org/NORAD/elements/gp.php?GROUP={group}&FORMAT=tle'
)


# ---------------------------------------------------------------------------
# Физические константы для расчётов
# ---------------------------------------------------------------------------

#: Радиус Земли в километрах. Используется для пересчёта радиус-вектора,
#: полученного при расчёте орбиты, в высоту над поверхностью.
EARTH_RADIUS_KM: float = 6371.0

#: Наклон земной оси к плоскости орбиты в градусах.
#: Значение определяет сезонное освещение планеты.
EARTH_AXIAL_TILT_DEGREES: float = 23.44

#: Julian Date, соответствующая нулевому моменту Unix-эпохи
#: (1970-01-01 00:00:00 по всемирному времени).
UNIX_EPOCH_JULIAN_DATE: float = 2440587.5
